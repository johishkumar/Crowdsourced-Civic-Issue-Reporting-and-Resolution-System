export const getTranslator = (lang) => {
  return (key, params = {}) => {
    const selected = translations[lang] || translations.en;
    let text = selected[key] || translations.en[key] || key;
    
    // Interpolate parameters like {name} or {count}
    Object.keys(params).forEach((placeholder) => {
      text = text.replace(`{${placeholder}}`, params[placeholder]);
    });
    return text;
  };
};
